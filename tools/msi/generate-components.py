#!/usr/bin/env python3
"""Generate WiX v4 ComponentGroup fragment from a staged MSI payload.

Portable (Linux/Windows). Output is included by packaging/msi/Semblon.wxs.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path
from xml.sax.saxutils import escape

FORBIDDEN_NAME_RE = re.compile(
    r"(buffalo_l|\.insightface|\.onnx$|antelopev2|w600k_r50)",
    re.IGNORECASE,
)


def _repo_root() -> Path:
    return Path(__file__).resolve().parents[2]


def _safe_id(prefix: str, rel: str) -> str:
    """WiX Ids: letters, digits, underscore; keep stable via short hash."""
    digest = hashlib.sha1(rel.encode("utf-8")).hexdigest()[:10]
    raw = re.sub(r"[^A-Za-z0-9_]", "_", f"{prefix}_{rel}")
    if not raw[0].isalpha():
        raw = "x_" + raw
    return f"{raw[:60]}_{digest}"


def _dir_id(rel_parent: str) -> str:
    if not rel_parent or rel_parent == ".":
        return "INSTALLFOLDER"
    return _safe_id("dir", rel_parent.replace("\\", "/"))


class DirNode:
    __slots__ = ("name", "rel", "children")

    def __init__(self, name: str, rel: str) -> None:
        self.name = name
        self.rel = rel
        self.children: dict[str, DirNode] = {}


def _ensure_path(root: DirNode, parts: tuple[str, ...]) -> None:
    node = root
    acc: list[str] = []
    for part in parts:
        acc.append(part)
        key = "/".join(acc)
        if part not in node.children:
            node.children[part] = DirNode(part, key)
        node = node.children[part]


def _emit_dirs(node: DirNode, lines: list[str], indent: int) -> None:
    pad = " " * indent
    for name in sorted(node.children):
        child = node.children[name]
        did = _dir_id(child.rel)
        if child.children:
            lines.append(f'{pad}<Directory Id="{did}" Name="{escape(child.name)}">')
            _emit_dirs(child, lines, indent + 2)
            lines.append(f"{pad}</Directory>")
        else:
            lines.append(f'{pad}<Directory Id="{did}" Name="{escape(child.name)}" />')


def generate(payload: Path, out_wxs: Path) -> int:
    if not payload.is_dir():
        raise SystemExit(f"payload not found: {payload} (run stage-payload.py first)")

    files = sorted(p for p in payload.rglob("*") if p.is_file())
    if not files:
        raise SystemExit(f"payload is empty: {payload}")

    tree = DirNode("", ".")
    dir_ids: dict[str, str] = {".": "INSTALLFOLDER"}
    for f in files:
        rel = f.relative_to(payload)
        if FORBIDDEN_NAME_RE.search(str(rel).replace("\\", "/")):
            raise SystemExit(f"REFUSED: forbidden path in payload: {rel}")
        parent = rel.parent
        if str(parent) != ".":
            _ensure_path(tree, parent.parts)
            acc: list[str] = []
            for part in parent.parts:
                acc.append(part)
                key = "/".join(acc)
                dir_ids[key] = _dir_id(key)

    lines: list[str] = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        "<!-- Generated by tools/msi/generate-components.py — do not edit by hand. -->",
        "<!-- Payload must NEVER contain buffalo_l / .onnx weights. -->",
        '<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs">',
        "  <Fragment>",
        '    <DirectoryRef Id="INSTALLFOLDER">',
    ]
    _emit_dirs(tree, lines, 6)
    lines.append("    </DirectoryRef>")
    lines.append("")
    lines.append('    <ComponentGroup Id="PayloadComponents">')

    for f in files:
        rel = f.relative_to(payload)
        rel_posix = rel.as_posix()
        parent_key = rel.parent.as_posix() if str(rel.parent) != "." else "."
        directory = dir_ids[parent_key]
        cid = _safe_id("cmp", rel_posix)
        fid = _safe_id("fil", rel_posix)
        source = "payload\\" + "\\".join(rel.parts)
        lines.append(f'      <Component Id="{cid}" Directory="{directory}" Guid="*">')
        lines.append(
            f'        <File Id="{fid}" Source="{escape(source)}" KeyPath="yes" />'
        )
        lines.append("      </Component>")

    lines.append("    </ComponentGroup>")
    lines.append("  </Fragment>")
    lines.append("</Wix>")
    lines.append("")

    out_wxs.parent.mkdir(parents=True, exist_ok=True)
    out_wxs.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {len(files)} File components -> {out_wxs}")
    return len(files)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--payload", type=Path, default=None)
    parser.add_argument("--out", type=Path, default=None)
    args = parser.parse_args(argv)
    repo = _repo_root()
    payload = (args.payload or (repo / "packaging" / "msi" / "payload")).resolve()
    out = (args.out or (repo / "packaging" / "msi" / "PayloadComponents.wxs")).resolve()
    generate(payload, out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
